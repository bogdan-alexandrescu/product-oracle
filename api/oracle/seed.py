"""Seed the single tenant, the admin user and a new API token.

    python -m oracle.seed [--email admin@example.com] [--password ...] [--token-name ...]

Idempotent for the tenant and the admin (existing ones are kept, the password is not
changed). Every run creates a NEW API token and prints it once; only its hash is stored.
"""

import argparse
import asyncio
import os
import secrets
import uuid
from dataclasses import dataclass

from sqlalchemy import select

from oracle.auth.models import User
from oracle.auth.service import create_api_token, create_user
from oracle.db import dispose_engine
from oracle.models import Tenant
from oracle.tenancy import tenant_session, unscoped_session


@dataclass
class SeedResult:
    tenant_id: uuid.UUID
    tenant_created: bool
    user_email: str
    user_created: bool
    password: str | None  # only when generated by this run
    token_name: str
    token: str


async def seed(
    *,
    tenant_name: str = "Example Co",
    email: str = "admin@example.com",
    password: str | None = None,
    token_name: str = "agent-track",
) -> SeedResult:
    async with unscoped_session() as s:
        tenant = await s.scalar(select(Tenant).order_by(Tenant.created_at).limit(1))
        tenant_created = tenant is None
        if tenant is None:
            tenant = Tenant(name=tenant_name)
            s.add(tenant)
            await s.commit()
        tenant_id = tenant.id

    generated = None
    async with tenant_session(tenant_id) as s:
        email = email.strip().lower()
        user = await s.scalar(select(User).where(User.email == email))
        user_created = user is None
        if user is None:
            if not password:
                password = generated = secrets.token_urlsafe(12)
            await create_user(s, email, password)
        _, raw = await create_api_token(s, token_name)
        await s.commit()

    return SeedResult(
        tenant_id=tenant_id,
        tenant_created=tenant_created,
        user_email=email,
        user_created=user_created,
        password=generated,
        token_name=token_name,
        token=raw,
    )


async def _main(args: argparse.Namespace) -> None:
    try:
        r = await seed(
            tenant_name=args.tenant_name,
            email=args.email,
            password=args.password,
            token_name=args.token_name,
        )
    finally:
        await dispose_engine()
    print(f"tenant   {r.tenant_id} ({'created' if r.tenant_created else 'existing'})")
    if r.user_created:
        print(f"admin    {r.user_email} (created)")
        if r.password:
            print(f"password {r.password}   <- generated, shown once")
    else:
        print(f"admin    {r.user_email} (existing, password unchanged)")
    print(f"token    {r.token}   <- '{r.token_name}', shown once; use as Bearer")


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    p.add_argument("--tenant-name", default="Example Co")
    p.add_argument("--email", default=os.environ.get("ORACLE_ADMIN_EMAIL", "admin@example.com"))
    p.add_argument("--password", default=os.environ.get("ORACLE_ADMIN_PASSWORD"))
    p.add_argument("--token-name", default="agent-track")
    asyncio.run(_main(p.parse_args()))


if __name__ == "__main__":
    main()
