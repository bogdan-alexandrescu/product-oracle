from oracle.roadmap import public as roadmap_public
from oracle.roadmap.models import RoadmapPublicCheck
from oracle.shares import service
from oracle.shares.models import ShareLink, ShareLinkView

router = APIRouter(prefix="/v1", tags=["shares"])

RUN_REFUSED = "Sharing outside the company is a person's act"
VIEW_NOTE = "Counts browsers, not people. Oracle never records who opened a link."
Expiry = Literal["24h", "7d", "14d", "30d", "90d"]
AudienceIn = Literal["board", "team", "engineering", "public"]


async def share_approver(principal: CurrentPrincipal) -> Principal:
    if principal.is_run or principal.run_token_id is not None:
        raise HTTPException(status.HTTP_403_FORBIDDEN, RUN_REFUSED)
    if not has_role(principal.role, "approver"):
        raise HTTPException(status.HTTP_403_FORBIDDEN, "Requires the approver role")
    return principal


async def share_owner(principal: CurrentPrincipal) -> Principal:
    if principal.is_run or principal.run_token_id is not None:
        raise HTTPException(status.HTTP_403_FORBIDDEN, RUN_REFUSED)
    if not has_role(principal.role, "owner"):
        raise HTTPException(status.HTTP_403_FORBIDDEN, "Requires the owner role")
    return principal


# Read by oracle.capabilities (#370).
share_approver.min_role = "approver"  # type: ignore[attr-defined]
share_owner.min_role = "owner"  # type: ignore[attr-defined]
Approver = Annotated[Principal, Depends(share_approver)]
Owner = Annotated[Principal, Depends(share_owner)]


class ShareLinkIn(BaseModel):
    publication_id: uuid.UUID
    audience: AudienceIn
    label: str = Field(min_length=1, max_length=120)
    expires_in: Expiry = service.DEFAULT_EXPIRY  # type: ignore[assignment]
    allow_download: bool = True
    # Set by the creator, or generated by Oracle when absent (O5-Q5); shown once.
    passcode: str | None = Field(
        default=None, min_length=service.PASSCODE_MIN, max_length=service.PASSCODE_MAX
    )


class ShareLinkPatch(BaseModel):
    # Extend: up to 90 days from now (O5-Q3).
    expires_in: Expiry | None = None
    # Move to a newer publication of the same document; the token stays (O5-Q6).
    publication_id: uuid.UUID | None = None


class PasscodeIn(BaseModel):
    passcode: str | None = Field(
        default=None, min_length=service.PASSCODE_MIN, max_length=service.PASSCODE_MAX
    )


class RevokeIn(BaseModel):
    reason: str | None = Field(default=None, max_length=500)


class RevokeAllIn(BaseModel):
    reason: str = Field(min_length=1, max_length=500)


class ShareDismissIn(BaseModel):
    ids: list[uuid.UUID] = Field(min_length=1, max_length=200)


class ShareLinkOut(BaseModel):
    id: uuid.UUID
    document: str
    publication_id: uuid.UUID
    publication_number: int
    version_number: int
    # The newest publication when it is newer than the link's ("Move to v<n>").
    newer_publication: int | None = None
    newer_version: int | None = None
    audience: AudienceIn
    label: str
    created_by: uuid.UUID
    created_by_name: str | None = None
    created_at: datetime
    expires_at: datetime
    state: Literal["active", "expired", "revoked"]
    revoked_at: datetime | None = None
    # Who revoked it (qa4-docs-share-30); none when it was revoked on its own.
    revoked_by: uuid.UUID | None = None
    revoked_by_name: str | None = None
    revoked_reason: str | None = None
    allow_download: bool
    views: int
    distinct_browsers: int
    last_viewed_at: datetime | None = None
    # Wrong passcodes locked the link until then (O5-Q5).
    locked_until: datetime | None = None


class ShareLinkCreated(BaseModel):
    link: ShareLinkOut
    # Shown once: neither is stored, so a lost one cannot be shown again.
    url: str
    passcode: str
    passcode_generated: bool
    expires_at: datetime


class PasscodeOut(BaseModel):
    link: ShareLinkOut
    passcode: str
    passcode_generated: bool


class ShareViewOut(BaseModel):
    viewed_at: datetime
    kind: Literal["page", "download"]
    browser_family: str | None = None
    country: str | None = None


class ShareDayOut(BaseModel):
    day: str
    views: int


class ShareViewsOut(BaseModel):
    link_id: uuid.UUID
    zone: str
    note: str = VIEW_NOTE
    views: int
    distinct_browsers: int
    entries: list[ShareViewOut]
    days: list[ShareDayOut]


class ShareRevokedCount(BaseModel):
    revoked: int


class ShareDismissedCount(BaseModel):
    dismissed: int


def _actor(principal: Principal) -> uuid.UUID:
    return principal.user_id or principal.id


async def _document(db, doc: str) -> Document:
    try:
        return await docs_service.get_document_or_404(db, doc)
    except docs_service.NotFoundError as e:
        raise HTTPException(status.HTTP_404_NOT_FOUND, str(e)) from e


def _shareable(document: Document) -> None:
    if document.kind != "roadmap":
        raise HTTPException(
            status.HTTP_422_UNPROCESSABLE_CONTENT,
            f"'{document.slug}' is a {document.kind}; share links are for roadmaps only",
        )
    if document.visibility != "company":
        raise HTTPException(
            status.HTTP_403_FORBIDDEN,
            "This document is limited to owners and approvers; it cannot be shared by link",
        )


async def _public_checked(db, publication: DocumentPublication, document: Document) -> bool:
    from oracle.docs.models import DocumentVersion

    check = await db.scalar(
        select(RoadmapPublicCheck)
        .where(RoadmapPublicCheck.publication_id == publication.id)
        .order_by(RoadmapPublicCheck.checked_at.desc(), RoadmapPublicCheck.id)
        .limit(1)
    )
    if check is None:
        return False
    version = await db.get(DocumentVersion, publication.version_id)
    review = await roadmap_public.review(db, document, version)
    return roadmap_public.check_state(check, roadmap_public.content_hash(review.page)) == "checked"


async def _publication_of(db, document: Document, publication_id: uuid.UUID):
    return await db.scalar(
        select(DocumentPublication).where(
            DocumentPublication.id == publication_id,
            DocumentPublication.document_id == document.id,
        )
    )


async def _outs(db, links: list[ShareLink]) -> list[ShareLinkOut]:
    if not links:
        return []
    ids = [link.id for link in links]
    pubs = {
        p.id: p
        for p in await db.scalars(
            select(DocumentPublication).where(
                DocumentPublication.id.in_({x.publication_id for x in links})
            )
        )
    }
    docs = {
        d.id: d
        for d in await db.scalars(
            select(Document).where(Document.id.in_({x.document_id for x in links}))
        )
    }
    newest = {
        row.document_id: row
        for row in (
            await db.execute(
                select(
                    DocumentPublication.document_id,
                    func.max(DocumentPublication.number).label("number"),
                    func.max(DocumentPublication.version_number).label("version"),
                )
                .where(DocumentPublication.document_id.in_(docs))
                .group_by(DocumentPublication.document_id)
            )
        ).all()
    }
    distinct = dict(
        (
            await db.execute(
                select(
                    ShareLinkView.share_link_id,
                    func.count(ShareLinkView.browser_key.distinct()),
                )
                .where(ShareLinkView.share_link_id.in_(ids))
                .group_by(ShareLinkView.share_link_id)
            )
        ).all()
    )
    users = {
        u.id: display_name(u.email, u.name)
        for u in await db.scalars(
            select(User).where(
                User.id.in_(
                    {x.created_by for x in links} | {x.revoked_by for x in links if x.revoked_by}
                )
            )
        )
    }
    out = []
    for link in links:
        pub, doc = pubs.get(link.publication_id), docs.get(link.document_id)
        last = newest.get(link.document_id)
        newer = last is not None and pub is not None and last.number > pub.number
        out.append(
            ShareLinkOut(
                id=link.id,
                document=doc.slug if doc else "",
                publication_id=link.publication_id,
                publication_number=pub.number if pub else 0,
                version_number=pub.version_number if pub else 0,
                newer_publication=last.number if newer else None,
                newer_version=last.version if newer else None,
                audience=link.audience,  # type: ignore[arg-type]
                label=link.label,
                created_by=link.created_by,
                created_by_name=users.get(link.created_by),
                created_at=link.created_at,
                expires_at=link.expires_at,
                state=service.state(link),  # type: ignore[arg-type]
                revoked_at=link.revoked_at,
                revoked_by=link.revoked_by,
                revoked_by_name=users.get(link.revoked_by) if link.revoked_by else None,
                revoked_reason=link.revoked_reason,
                allow_download=link.allow_download,
                views=link.views,
                distinct_browsers=distinct.get(link.id, 0),
                last_viewed_at=link.last_viewed_at,
                locked_until=link.locked_until
                if link.locked_until and link.locked_until > service.now()
                else None,
            )
        )
    return out


async def _link(db, link_id: uuid.UUID, *, lock: bool = False) -> ShareLink:
    link = await db.get(ShareLink, link_id, with_for_update=lock or None)
    if link is None:
        raise HTTPException(status.HTTP_404_NOT_FOUND, "share link not found")
    return link


def _creator_or_owner(principal: Principal, link: ShareLink) -> None:
    if has_role(principal.role, "owner") or _actor(principal) == link.created_by:
        return
    raise HTTPException(
        status.HTTP_403_FORBIDDEN, "Only the link's creator or an owner can change it"
    )


def _url(token: str) -> str:
    from oracle.export.render import app_url

    return app_url(f"/s/{token}")


@router.get("/documents/{doc}/share-links", response_model=list[ShareLinkOut])
async def list_share_links(doc: str, principal: Approver, db: TenantDB) -> list[ShareLinkOut]:
    """The document's share links, newest first: label, audience, version, creator,
    expiry, views (distinct browsers), last viewed and state. Never a token, a URL or a
    passcode: those are shown once."""
    document = await _document(db, doc)
    links = list(
        await db.scalars(
            select(ShareLink)
            .where(ShareLink.document_id == document.id)
            .order_by(ShareLink.created_at.desc(), ShareLink.id)
        )
    )
    return await _outs(db, links)


@router.post(
    "/documents/{doc}/share-links",
    response_model=ShareLinkCreated,
    status_code=status.HTTP_201_CREATED,
    responses={
        403: {"description": "Public below owner, a run's token, or an approvers-only document"},
        409: {"description": "not_published, or no_public_check for the Public audience"},
        422: {"description": "Not a roadmap, an expiry past 90 days, or a short passcode"},
    },
)
async def create_share_link(
    doc: str, body: ShareLinkIn, principal: Approver, db: TenantDB
) -> ShareLinkCreated:
    """Make a link to one publication in one audience, with a passcode (set here, or
    generated by Oracle) and an expiry (14 days unless chosen, 90 at most). The link's
    address and passcode are returned once."""
    document = await _document(db, doc)
    _shareable(document)
    if body.audience == "public" and not has_role(principal.role, "owner"):
        raise HTTPException(status.HTTP_403_FORBIDDEN, "Only an owner can share the Public version")
    publication = await _publication_of(db, document, body.publication_id)
    if publication is None:
        raise HTTPException(
            status.HTTP_409_CONFLICT,
            {"code": "not_published", "message": "Publish this version first"},
        )
    if body.audience == "public" and not await _public_checked(db, publication, document):
        raise HTTPException(
            status.HTTP_409_CONFLICT,
            {"code": "no_public_check",
             "message": "Check the public version of this publication first"},
        )  # fmt: skip
    generated = body.passcode is None
    passcode = service.generate_passcode() if generated else str(body.passcode)
    raw, token_hash = service.new_token()
    link = ShareLink(
        id=uuid.uuid4(),
        document_id=document.id,
        publication_id=publication.id,
        audience=body.audience,
        label=body.label.strip() or body.label,
        token_hash=token_hash,
        passcode_hash=await asyncio.to_thread(service.hash_passcode, passcode),
        passcode_version=1,
        passcode_failures=0,
        created_by=_actor(principal),
        expires_at=service.expires_from(body.expires_in),
        allow_download=body.allow_download,
        follow_latest=False,
        views=0,
        refused_in_window=0,
    )
    db.add(link)
    await db.flush()
    await audit.record(
        db, principal, "share_link.created", "share_link", link.id,
        {"document_id": str(document.id), "publication": publication.number,
         "audience": body.audience, "label": link.label, "expires_in": body.expires_in,
         "allow_download": body.allow_download, "passcode_generated": generated},
    )  # fmt: skip
    await db.commit()
    await db.refresh(link)
    out = (await _outs(db, [link]))[0]
    return ShareLinkCreated(
        link=out,
        url=_url(raw),
        passcode=passcode,
        passcode_generated=generated,
        expires_at=link.expires_at,
    )


@router.patch("/share-links/{link_id}", response_model=ShareLinkOut)
async def update_share_link(
    link_id: uuid.UUID, body: ShareLinkPatch, principal: Approver, db: TenantDB
) -> ShareLinkOut:
    """Extend (up to 90 days from now) or move the link to another publication of its
    document (the token stays). The creator or an owner; audited."""
    link = await _link(db, link_id, lock=True)
    _creator_or_owner(principal, link)
    if link.revoked_at is not None:
        raise HTTPException(
            status.HTTP_409_CONFLICT, "This link is revoked; make a new one instead"
        )
    document = await db.get(Document, link.document_id)
    if body.expires_in is not None:
        before = link.expires_at
        link.expires_at = service.expires_from(body.expires_in)
        await audit.record(
            db, principal, "share_link.extended", "share_link", link.id,
            {"before": before.isoformat(), "after": link.expires_at.isoformat()},
        )  # fmt: skip
    if body.publication_id is not None and body.publication_id != link.publication_id:
        publication = await _publication_of(db, document, body.publication_id)
        if publication is None:
            raise HTTPException(status.HTTP_404_NOT_FOUND, "publication not found")
        if link.audience == "public" and not await _public_checked(db, publication, document):
            raise HTTPException(
                status.HTTP_409_CONFLICT,
                {"code": "no_public_check",
                 "message": "Check the public version of this publication first"},
            )  # fmt: skip
        before_pub = link.publication_id
        link.publication_id = publication.id
        await audit.record(
            db, principal, "share_link.moved", "share_link", link.id,
            {"before": str(before_pub), "after": str(publication.id),
             "publication": publication.number},
        )  # fmt: skip
    await db.commit()
    await db.refresh(link)
    return (await _outs(db, [link]))[0]


@router.post("/share-links/{link_id}/passcode", response_model=PasscodeOut)
async def rotate_share_link_passcode(
    link_id: uuid.UUID, body: PasscodeIn, principal: Approver, db: TenantDB
) -> PasscodeOut:
    """A new passcode (set here, or generated), shown once. The link and its address stay;
    every browser that opened it with the old passcode must enter the new one."""
    link = await _link(db, link_id, lock=True)
    _creator_or_owner(principal, link)
    if link.revoked_at is not None:
        raise HTTPException(status.HTTP_409_CONFLICT, "This link is revoked")
    generated = body.passcode is None
    passcode = service.generate_passcode() if generated else str(body.passcode)
    link.passcode_hash = await asyncio.to_thread(service.hash_passcode, passcode)
    link.passcode_version += 1
    link.passcode_failures, link.passcode_window_start, link.locked_until = 0, None, None
    await audit.record(
        db, principal, "share_link.passcode_rotated", "share_link", link.id,
        {"passcode_generated": generated},
    )  # fmt: skip
    await db.commit()
    await db.refresh(link)
    return PasscodeOut(
        link=(await _outs(db, [link]))[0], passcode=passcode, passcode_generated=generated
    )


@router.post("/share-links/{link_id}/revoke", response_model=ShareLinkOut)
async def revoke_share_link(
    link_id: uuid.UUID, body: RevokeIn, principal: Approver, db: TenantDB
) -> ShareLinkOut:
    """End the link now (the next request is refused). The creator, an owner, or any
    approver for a non-public link. It cannot be undone: make a new link instead."""
    link = await _link(db, link_id, lock=True)
    if link.audience == "public":
        _creator_or_owner(principal, link)
    await service.revoke(db, principal, link, body.reason, _actor(principal))
    # A person revoked it: nothing for the owners' Inbox.
    link.inbox_dismissed_at = link.inbox_dismissed_at or service.now()
    await db.commit()
    await db.refresh(link)
    return (await _outs(db, [link]))[0]


@router.post("/documents/{doc}/share-links/revoke-all", response_model=ShareRevokedCount)
async def revoke_all_share_links(
    doc: str, body: RevokeAllIn, principal: Owner, db: TenantDB
) -> ShareRevokedCount:
    """Revoke every live link on the document (owners)."""
    document = await _document(db, doc)
    links = list(
        await db.scalars(
            select(ShareLink)
            .where(ShareLink.document_id == document.id, ShareLink.revoked_at.is_(None))
            .with_for_update()
        )
    )
    for link in links:
        await service.revoke(db, principal, link, body.reason, _actor(principal), all=True)
        link.inbox_dismissed_at = service.now()
    await db.commit()
    return ShareRevokedCount(revoked=len(links))


@router.post("/share-links/dismiss", response_model=ShareDismissedCount)
async def dismiss_share_revocations(
    body: ShareDismissIn, principal: Owner, db: TenantDB
) -> ShareDismissedCount:
    """Dismiss the owners' Inbox row of links revoked because their creator left, was
    demoted, or their document changed (O5-Q10)."""
    links = list(
        await db.scalars(
            select(ShareLink).where(
                ShareLink.id.in_(body.ids),
                ShareLink.revoked_at.is_not(None),
                ShareLink.inbox_dismissed_at.is_(None),
            )
        )
    )
    for link in links:
        link.inbox_dismissed_at = service.now()
    if links:
        await audit.record(
            db, principal, "share_link.inbox_dismissed", "share_link", links[0].id,
            {"ids": [str(x.id) for x in links]},
        )  # fmt: skip
    await db.commit()
    return ShareDismissedCount(dismissed=len(links))


@router.get("/share-links/{link_id}/views", response_model=ShareViewsOut)
async def share_link_views(
    link_id: uuid.UUID,
    principal: Approver,
    db: TenantDB,
    from_: Annotated[datetime | None, Query(alias="from")] = None,
    to: Annotated[datetime | None, Query()] = None,
) -> ShareViewsOut:
    """The view log: when the link was opened (page or download), the browser family and
    the country when the load balancer gives one, per day, and the distinct-browser
    count. It never records who opened it (O5-Q4)."""
    link = await _link(db, link_id)
    query = select(ShareLinkView).where(ShareLinkView.share_link_id == link.id)
    if from_ is not None:
        query = query.where(ShareLinkView.viewed_at >= from_)
    if to is not None:
        query = query.where(ShareLinkView.viewed_at < to)
    rows = list(await db.scalars(query.order_by(ShareLinkView.viewed_at.desc()).limit(5000)))
    zone = await company_time.company_time_zone(db)
    days = Counter(company_time.day(r.viewed_at, zone).isoformat() for r in rows)
    return ShareViewsOut(
        link_id=link.id,
        zone=zone,
        views=len(rows),
        distinct_browsers=len({r.browser_key for r in rows}),
        entries=[
            ShareViewOut(
                viewed_at=r.viewed_at,
                kind=r.kind,
                browser_family=r.browser_family,  # type: ignore[arg-type]
                country=r.country,
            )
            for r in rows
        ],  # fmt: skip
        days=[ShareDayOut(day=d, views=n) for d, n in sorted(days.items())],
    )
