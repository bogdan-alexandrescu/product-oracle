"""Members' share-link routes (spec-O5 §3, API; owner answers O5 Q1, Q3, Q5, Q6, Q9).

Approvers and owners make Board, Team and Engineering links; owners only make Public
ones, and only for a publication whose public check still holds (O5-Q1). Only from a
person: the signed-in browser or a personal API token of that role; a run's token is
403 ("Sharing outside the company is a person's act", H11 ``external_messages``).
The link's token and passcode are returned once, at creation (and the passcode again
only by a rotation, which keeps the token); no read returns either.
"""

