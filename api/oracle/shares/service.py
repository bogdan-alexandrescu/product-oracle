"""Share links: tokens, passcodes, expiry, states, the view log's keys, and the
revocations a member's leaving or a document's change makes (spec-O5 §3).

Owner answer O5-Q5 (changed from the spec): every link has a passcode, set by its creator
or generated by Oracle and shown once. Only a slow hash (argon2, as members' passwords:
``oracle.auth.service``) is kept, compared in constant time by argon2 itself; a rotation
keeps the token and bumps ``passcode_version``, which ends every cookie signed before it.
"""

import hashlib
import hmac
import secrets
import uuid
from datetime import UTC, datetime, timedelta
from typing import Any

from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession

from oracle import audit
from oracle.auth.service import hash_password, verify_password
from oracle.shares.models import ShareLink

EXPIRY_CHOICES = {
    "24h": timedelta(hours=24),
    "7d": timedelta(days=7),
    "14d": timedelta(days=14),
    "30d": timedelta(days=30),
    "90d": timedelta(days=90),
}
DEFAULT_EXPIRY = "14d"
MAX_EXPIRY = timedelta(days=90)
PASSCODE_MIN, PASSCODE_MAX = 8, 128
# No look-alikes (0/O, 1/l/I): read aloud or typed from a message.
_ALPHABET = "abcdefghjkmnpqrstuvwxyz23456789"
_GROUPS, _GROUP = 4, 4  # 16 characters from 31: about 79 bits

# Revocation reasons that put a row in the owners' Inbox (O5-Q10).
CREATOR_REMOVED = "creator removed"
CREATOR_DEMOTED = "creator's role changed"
DOCUMENT_TRASHED = "document moved to Trash"
DOCUMENT_LIMITED = "document limited to owners and approvers"
INBOX_REASONS = (CREATOR_REMOVED, CREATOR_DEMOTED, DOCUMENT_TRASHED, DOCUMENT_LIMITED)


def now() -> datetime:
    """The clock (tests move it)."""
    return datetime.now(UTC)


def hash_token(raw: str) -> str:
    # 256-bit random secrets: a fast hash is enough (no brute force), as for API tokens.
    return hashlib.sha256(raw.encode()).hexdigest()


def new_token() -> tuple[str, str]:
    """A new link token (32 random bytes, URL-safe) and its sha256."""
    raw = secrets.token_urlsafe(32)
    return raw, hash_token(raw)


def generate_passcode() -> str:
    return "-".join(
        "".join(secrets.choice(_ALPHABET) for _ in range(_GROUP)) for _ in range(_GROUPS)
    )


def hash_passcode(passcode: str) -> str:
    return hash_password(passcode)


def verify_passcode(passcode_hash: str, passcode: str) -> bool:
    return verify_password(passcode_hash, passcode)


# Verified when no link matches, so a guess at a token takes the time a real one does.
_DUMMY_HASH = hash_passcode(secrets.token_urlsafe(16))


def verify_or_waste(passcode_hash: str | None, passcode: str) -> bool:
    if passcode_hash is None:
        verify_passcode(_DUMMY_HASH, passcode)
        return False
    return verify_passcode(passcode_hash, passcode)


def browser_key(secret: str, cookie_id: str) -> str:
    """HMAC(link secret, cookie id): the same browser on one link counts once; nothing
    ties it to another link or to the cookie's value."""
    return hmac.new(secret.encode(), cookie_id.encode(), hashlib.sha256).hexdigest()


def browser_family(user_agent: str | None) -> str:
    ua = user_agent or ""
    if "Edg/" in ua:
        return "Edge"
    if "Firefox/" in ua:
        return "Firefox"
    if "Chrome/" in ua or "CriOS/" in ua:
        return "Chrome"
    if "Safari/" in ua:
        return "Safari"
    return "Other"


def state(link: ShareLink, at: datetime | None = None) -> str:
    if link.revoked_at is not None:
        return "revoked"
    if link.expires_at <= (at or now()):
        return "expired"
    return "active"


def expires_from(choice: str, at: datetime | None = None) -> datetime:
    return (at or now()) + EXPIRY_CHOICES[choice]


async def revoke(
    db: AsyncSession,
    actor: Any,
    link: ShareLink,
    reason: str | None,
    revoked_by: uuid.UUID | None,
    **data: Any,
) -> bool:
    """Revoke ``link`` (audited ``share_link.revoked``); False when it already was."""
    if link.revoked_at is not None:
        return False
    link.revoked_at = now()
    link.revoked_by = revoked_by
    link.revoked_reason = reason
    await audit.record(
        db, actor, "share_link.revoked", "share_link", link.id,
        {"document_id": str(link.document_id), "reason": reason, **data},
    )  # fmt: skip
    return True


async def revoke_created_by(
    db: AsyncSession,
    actor: Any,
    creators: set[uuid.UUID],
    reason: str,
    audiences: set[str] | None = None,
) -> int:
    """A member's disable or demotion below approver (O5-Q10): revoke the live links
    they (or their API tokens) created; owners see them in the Inbox to re-share. An
    owner demoted to approver passes ``audiences={"public"}``: a Public link is an
    owner's, the others stay theirs."""
    if not creators:
        return 0
    query = select(ShareLink).where(
        ShareLink.created_by.in_(creators), ShareLink.revoked_at.is_(None)
    )
    if audiences is not None:
        query = query.where(ShareLink.audience.in_(audiences))
    links = await db.scalars(query.with_for_update())
    by = getattr(actor, "user_id", None) or getattr(actor, "id", None)
    return sum([await revoke(db, actor, link, reason, by) for link in links])


async def revoke_documents(
    db: AsyncSession, actor: Any, document_ids: set[uuid.UUID], reason: str
) -> int:
    """A trash, or a document limited to owners and approvers: every link on it ends at
    once. A restore brings none back."""
    if not document_ids:
        return 0
    from oracle.trash.filter import INCLUDE_TRASHED

    links = await db.scalars(
        select(ShareLink)
        .where(ShareLink.document_id.in_(document_ids), ShareLink.revoked_at.is_(None))
        .with_for_update()
        .execution_options(**{INCLUDE_TRASHED: True})
    )
    by = getattr(actor, "user_id", None) or getattr(actor, "id", None)
    return sum([await revoke(db, actor, link, reason, by) for link in links])


async def inbox_rows(db: AsyncSession) -> list[dict[str, Any]]:
    """Owners' Inbox (O5-Q10): links revoked because their creator left or was demoted,
    or their document changed, grouped by creator or document and reason, newest first,
    until dismissed. Each row offers Re-share (the link's document and audience)."""
    from oracle.auth.models import User
    from oracle.docs.models import Document
    from oracle.members.names import display_name

    rows = (
        await db.execute(
            select(ShareLink, Document.slug, Document.title)
            .join(Document, Document.id == ShareLink.document_id)
            .where(
                ShareLink.revoked_at.is_not(None),
                ShareLink.inbox_dismissed_at.is_(None),
                ShareLink.revoked_reason.in_(INBOX_REASONS),
            )
            .order_by(ShareLink.revoked_at.desc(), ShareLink.id)
        )
    ).all()
    if not rows:
        return []
    creators = {link.created_by for link, _, _ in rows}
    names = {
        u.id: display_name(u.email, u.name)
        for u in await db.scalars(select(User).where(User.id.in_(creators)))
    }
    groups: dict[tuple, dict[str, Any]] = {}
    for link, slug, title in rows:
        by_creator = link.revoked_reason in (CREATOR_REMOVED, CREATOR_DEMOTED)
        key = (link.revoked_reason, link.created_by if by_creator else link.document_id)
        group = groups.setdefault(
            key,
            {
                "reason": link.revoked_reason,
                "creator_id": link.created_by if by_creator else None,
                "creator_name": names.get(link.created_by) if by_creator else None,
                "document_title": None if by_creator else title,
                "revoked_at": link.revoked_at,
                "links": [],
            },
        )
        group["links"].append(
            {"id": link.id, "label": link.label, "document": slug, "document_title": title,
             "audience": link.audience, "publication_id": link.publication_id}
        )  # fmt: skip
    out = []
    for group in groups.values():
        n = len(group["links"])
        count = f"{n} link" if n == 1 else f"{n} links"
        who = group["creator_name"] or "A member"
        what = {
            CREATOR_REMOVED: f"{who} left",
            CREATOR_DEMOTED: f"{who}'s role changed",
            DOCUMENT_TRASHED: f"{group['document_title']} moved to Trash",
            DOCUMENT_LIMITED: f"{group['document_title']} limited to owners and approvers",
        }[group["reason"]]
        out.append({**group, "title": f"Links revoked: {what} · {count}"})
    return out
