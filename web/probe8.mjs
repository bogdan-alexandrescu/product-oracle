const b = await chromium.launch();
const page = await b.newPage({ viewport: { width: 1440, height: 900 } });
await page.goto("http://localhost:3393/login?next=%2Fhome");
await page.getByLabel("Email").fill("admin@example.com");
await page.getByLabel("Password").fill("demo");
await page.getByRole("button", { name: "Sign in" }).click();
await page.waitForURL(/\/home$/);
const rows = async () => { await page.goto("http://localhost:3393/inbox"); await page.waitForTimeout(2500); return (await page.getByTestId("inbox-proposals").first().innerText()).split("\n").filter((l) => l.trim()).slice(0, 60); };
const cnt = async () => (await page.getByTestId("simple-nav-inbox-count").allTextContents())[0];
const r1 = await rows(); console.log("count1", await cnt());
const link = page.getByTestId("inbox-proposals").getByRole("link", { name: "Open Weekly alert digest on its roadmap" }).first();
console.log("links", await link.count());
await link.click(); await page.waitForTimeout(2500);
const prop = page.getByTestId("decision-tray").getByTestId("tray-proposal").filter({ hasText: "Weekly alert digest" }).first();
console.log("prop:", await prop.innerText());
await prop.getByRole("button", { name: "Accept" }).click(); await page.waitForTimeout(2500);
console.log("count after", await cnt());
const r2 = await rows(); console.log("count2", await cnt());
console.log("REMOVED:", r1.filter((x) => !r2.includes(x)).join(" | "));
console.log("ADDED:", r2.filter((x) => !r1.includes(x)).join(" | "));
await b.close();
